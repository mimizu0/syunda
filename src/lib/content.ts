const POOLS: Record<ModeId, PromptItem[]> = {
  word: WORDS,
  mid: MIDS,
  long: LONGS,
};

export function pickItem(mode: ModeId, avoid: PromptItem[] = []): PromptItem {
  const pool = POOLS[mode];
  const blocked = new Set(avoid);
  const candidates = pool.filter((item) => !blocked.has(item));
  const source = candidates.length ? candidates : pool;
  return source[Math.floor(Math.random() * source.length)]!;
}

export function kanaCount(item: PromptItem): number {
  return readingOf(item).replace(/[。、！？・]/g, "").length;
}
